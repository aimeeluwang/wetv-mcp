/**
 * 生成模拟剧集列表
 */
export function generateEpisodes(contentId: string): Episode[] {
  const content = CONTENT_DB.find(c => c.id === contentId);
  if (!content) return [];
  
  const episodes: Episode[] = [];
  const episodeCount = content.aired_episodes;
  
  for (let i = 1; i <= episodeCount; i++) {
    episodes.push({
      episode_index: i,
      episode_name: content.type === 'movie' 
        ? content.title 
        : `第 ${i} 集`,
      duration_minutes: content.type === 'movie' 
        ? 135 
        : content.type === 'anime' ? 24 : 45,
      play_url: `${content.play_url}?ep=${i}`,
      subtitle_languages: content.subtitle_languages,
      air_date: getAirDate(content.release_year, i, content.update_schedule),
      brief: `${content.title} 第 ${i} 集`,
    });
  }
  
  return episodes;
}

function getAirDate(year: number, ep: number, schedule: string): string {
  const baseDate = new Date(year, 0, 15); // Jan 15
  baseDate.setDate(baseDate.getDate() + (ep - 1) * 3); // 每 3 天一集
  return baseDate.toISOString().split('T')[0];
}

